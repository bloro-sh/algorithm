"""
[동적 프로그래밍 - 계단 오르기 (상향식 / Bottom-up)]

문제 설명:
- 상향식 DP로 계단을 오르는 방법의 수를 계산합니다.
- 한 번에 1칸 또는 2칸을 오를 수 있습니다.
- n번째 계단까지 오르는 경우의 수를 구합니다.

입력:
- n: 계단의 수

출력:
- n번째 계단까지 오르는 방법의 수

예제:
입력: n = 4
출력: 5
설명: 
  1. 1+1+1+1
  2. 1+1+2
  3. 1+2+1
  4. 2+1+1
  5. 2+2

힌트:
- dp[i] = 계단 i까지 오르는 방법의 수
- dp[i] = dp[i-1] + dp[i-2]
- 작은 문제부터 차례로 계산

DP 문제 풀이 순서:
1. 부분 문제 정의: dp[i]가 무엇인지 정의
2. 점화식 도출: dp[i]를 이전 값으로 표현
3. 초기값 설정: dp[0], dp[1] 등
4. 계산 순서 결정: 상향식 or 하향식
5. 구현 및 검증
"""

def climb_stairs(n):
    """
    계단 오르기 (상향식 DP)
    
    Args:
        n: 계단의 수
    
    Returns:
        n번째 계단까지 오르는 방법의 수
    """
    if n <= 1:
        return 1
        
    # TODO: 특별한 경우 처리
    pass
    #dp테이블 설정
    dp = [0]*(n+1)
    # TODO: dp 배열 생성 및 초기화
    pass


    #초기값 설정
    dp[0] = 1
    dp[1] = 1

    #상향식 반복문으로 작은 문제 부터 큰 문제 해결
    for i in range(2,n+1):
        dp[i] = dp[n-1]+dp[i-2]
    # TODO: 작은 문제부터 차례로 계산
    pass

    return dp[n]